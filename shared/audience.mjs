export const audiencePage = (page) =>
  audiencePages.includes(page) ? page : "other";
export const audienceRetentionDays = 90;
export function audienceAllowed(status, cookie = "", gpc = false) {
  return (
    !!status?.enabled &&
    !status.optedOut &&
    !status.globalPrivacyControl &&
    !gpc &&
    !String(cookie)
      .split(";")
      .some((v) => v.trim() === "anipic_audience_off=1")
  );
}
